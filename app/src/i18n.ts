/** Look a display string up by its English key; unknown keys render as-is. */
export function t(locale: Locale, key: string): string {
  const entry = DICT[key];
  if (!entry) return key;
  return entry[locale] ?? entry.en;
}

/** A dictionary line with its {holes} filled. */
export function tFill(locale: Locale, key: string, vars: Record<string, string>): string {
  let out = t(locale, key);
  for (const [name, value] of Object.entries(vars)) out = out.split(`{${name}}`).join(value);
  return out;
}

/** The words of a refusal on the error page. English stays exactly as thrown;
 * Spanish reads the dictionary line when there is one. */
export function refusalText(locale: Locale, err: { message: string; words?: { key: string; vars: Record<string, string> } }): string {
  if (locale === "en") return err.message;
  return err.words ? tFill(locale, err.words.key, err.words.vars) : t(locale, err.message);
}
