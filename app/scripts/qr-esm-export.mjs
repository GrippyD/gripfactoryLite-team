/**
 * One-shot mechanical export: turn Nayuki's namespace TypeScript into an ES
 * module so isolatedModules can typecheck it. The original
 * src/vendor/qrcodegen.ts is never edited.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const raw = readFileSync(join(root, "src/vendor/qrcodegen.ts"), "utf8");
const license = raw.slice(0, raw.indexOf("*/") + 2);

const nsOpen = raw.indexOf("namespace qrcodegen {");
const helperMark = raw.indexOf("/*---- Public helper enumeration ----*/");
let main = raw.slice(nsOpen + "namespace qrcodegen {".length, helperMark);
const lastBrace = main.lastIndexOf("}");
main = main.slice(0, lastBrace);

const eccNs = raw.slice(raw.indexOf("namespace qrcodegen.QrCode {"), raw.indexOf("namespace qrcodegen.QrSegment {"));
const eccClassStart = eccNs.indexOf("export class Ecc {");
const eccClass = eccNs.slice(eccClassStart, eccNs.lastIndexOf("}") + 1);

const modeNs = raw.slice(raw.indexOf("namespace qrcodegen.QrSegment {"));
const modeClassStart = modeNs.indexOf("export class Mode {");
let modeClass = modeNs.slice(modeClassStart);
modeClass = modeClass.replace(/\}\s*\}\s*$/, "}");

main = main
  .replaceAll("qrcodegen.QrSegment", "QrSegment")
  .replaceAll("QrCode.Ecc", "Ecc")
  .replaceAll("QrSegment.Mode", "Mode");

const out = `${license}

/* Mechanical ES module export of the Nayuki file above. Algorithm untouched.
 * Generated by scripts/qr-esm-export.mjs so isolatedModules can compile it.
 */

type bit = number;
type byte = number;
type int = number;

${eccClass}

${modeClass}

${main}
`;

writeFileSync(join(root, "src/vendor/qr-esm.ts"), out, "utf8");
console.log("wrote src/vendor/qr-esm.ts", out.length);
